"""Exports for a built robot: FBX for Roblox, rig JSON for inspection, and the generated Luau rig module."""

import json
import os

import bpy


def number(value):
    text = ("%.4f" % value).rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def vector3(vector):
    return "Vector3.new(%s, %s, %s)" % tuple(number(value) for value in vector)


def export_fbx(robot, folder):
    path = os.path.join(folder, robot.name + ".fbx")
    for obj in bpy.context.view_layer.objects:
        obj.select_set(False)
    for part in robot.parts:
        part.obj.select_set(True)
    bpy.context.view_layer.objects.active = robot.parts[0].obj
    bpy.ops.export_scene.fbx(
        filepath=path,
        use_selection=True,
        object_types={"MESH"},
        axis_forward="-Z",
        axis_up="Y",
        # Blender writes centimeters (100 per unit) and Roblox reads the numbers as studs, so scale by 0.01 to keep
        # 1 unit = 1 stud.
        global_scale=0.01,
        mesh_smooth_type="FACE",
        add_leaf_bones=False,
        bake_anim=False,
    )
    return path


def export_json(robot, roles, folder):
    data = {
        "name": robot.name,
        "joints": [
            {"name": joint.name, "parent": joint.parent, "pivot": [round(value, 4) for value in joint.pivot]}
            for joint in robot.joints
        ],
        "parts": [
            {
                "name": part.name,
                "joint": part.joint,
                "role": part.role,
                "center": [round(value, 4) for value in part.center],
                "size": [round(value, 4) for value in part.size],
                "triangles": part.triangles,
            }
            for part in robot.parts
        ],
        "roles": roles,
    }
    path = os.path.join(folder, robot.name + ".rig.json")
    with open(path, "w", encoding="ascii") as handle:
        json.dump(data, handle, indent=1)
    return path


def luau_rig(robot, roles):
    """One frame's entry in the generated RobotRigs module."""
    lines = [
        "\t%s = {" % robot.name,
        "\t\troles = {",
    ]
    for role, style in roles.items():
        lines.append(
            "\t\t\t%s = { color = Color3.new(%s, %s, %s), material = Enum.Material.%s, tint = %s },"
            % (
                role,
                number(style["color"][0]),
                number(style["color"][1]),
                number(style["color"][2]),
                style["material"],
                "true" if style["tint"] else "false",
            )
        )
    lines += ["\t\t},", "\t\tjoints = {"]
    for joint in robot.joints:
        lines.append(
            '\t\t\t{ name = "%s", parent = "%s", pivot = %s },' % (joint.name, joint.parent or "", vector3(joint.pivot))
        )
    lines += ["\t\t},", "\t\tparts = {"]
    for part in robot.parts:
        lines.append(
            '\t\t\t{ name = "%s", joint = "%s", role = "%s", center = %s, size = %s },'
            % (part.name, part.joint, part.role, vector3(part.center), vector3(part.size))
        )
    lines += ["\t\t},", "\t},"]
    return lines


def export_luau(entries, path):
    """Writes the RobotRigs module with every frame. entries is [(robot, roles)]."""
    lines = [
        "--!strict",
        "",
        "-- Generated by art/build_robot.py from the Blender rig definitions. Do not edit by hand.",
        "",
        "return {",
    ]
    for robot, roles in entries:
        lines += luau_rig(robot, roles)
    lines += ["}", ""]
    with open(path, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(lines))
    return path


def luau_clips(poses, clips):
    lines = [
        "--!strict",
        "",
        "-- Generated by art/build_robot.py from art/poses.py. Do not edit by hand.",
        "-- Angles are degrees for CFrame.fromEulerAnglesYXZ(rx, ry, rz) about each joint, in its parent's frame.",
        "",
        "return {",
        "\tposes = {",
    ]
    for name in sorted(poses):
        pose = poses[name]
        lines.append("\t\t%s = {" % name)
        lines.append("\t\t\tpos = %s," % vector3(pose["pos"]))
        lines.append("\t\t\trot = {")
        for joint in sorted(pose["rot"]):
            angles = pose["rot"][joint]
            if any(abs(value) > 1e-6 for value in angles):
                lines.append("\t\t\t\t%s = %s," % (joint, vector3(angles)))
        lines += ["\t\t\t},", "\t\t},"]
    lines += ["\t},", "\tclips = {"]
    for name in sorted(clips):
        clip = clips[name]
        extra = ""
        if "period" in clip:
            extra = ", period = %s" % number(clip["period"])
        lines.append('\t\t%s = { kind = "%s"%s, keys = {' % (name, clip["kind"], extra))
        for u, pose, ease in clip["keys"]:
            lines.append('\t\t\t{ u = %s, pose = "%s", ease = "%s" },' % (number(u), pose, ease))
        lines.append("\t\t} },")
    lines += ["\t},", "}", ""]
    return "\n".join(lines)


def export_clips(poses, clips, path):
    with open(path, "w", encoding="ascii", newline="\n") as handle:
        handle.write(luau_clips(poses, clips))
    return path
