param(
    [string]$Name = 'Anvil',
    [long]$UserId = 0,
    [long]$GroupId = 0,
    [switch]$DryRun
)

# Uploads art/build/<Name>.fbx (from ./scripts/art.ps1) as a Roblox Model through Open Cloud and records its asset ID in
# src/shared/RobotAssets.luau. A robot that already has an ID gets a new version of the same asset, so the ID stays.
# The key needs the Assets API with Read and Write; store it with ./scripts/api-key.ps1 -Set. Without -UserId or
# -GroupId the models are created under the user who owns the key. Roblox only loads models owned by the account or group
# that owns the experience, so upload with the owner's key.
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'api-key.ps1')

$root = Split-Path -Parent $PSScriptRoot
$manifest = Join-Path $root 'src/shared/RobotAssets.luau'
$file = Join-Path $root "art/build/$Name.fbx"
if (-not (Test-Path $file)) {
    throw "$file is missing; run ./scripts/art.ps1 first."
}
if (($UserId -gt 0) -and ($GroupId -gt 0)) {
    throw 'Pass at most one of -UserId or -GroupId.'
}

$source = [System.IO.File]::ReadAllText($manifest)
$pattern = "(?m)^(\s*$Name = \{ Id = )(\d+)( \},)"
$match = [regex]::Match($source, $pattern)
if (-not $match.Success) {
    throw "No $Name entry in RobotAssets.luau."
}
$assetId = [long]$match.Groups[2].Value
$action = if ($assetId -gt 0) { "new version of asset $assetId" } else { 'new asset' }
if ($DryRun) {
    Write-Output ("{0}: {1} ({2} KB)" -f $Name, $action, [math]::Round((Get-Item $file).Length / 1KB))
    Write-Output 'PASS: dry run (nothing uploaded)'
    return
}

Add-Type -AssemblyName System.Net.Http
$apiKey = Get-RobloxApiKey
$client = New-Object System.Net.Http.HttpClient
$client.Timeout = [TimeSpan]::FromSeconds(300)
$client.DefaultRequestHeaders.Add('x-api-key', $apiKey)
try {
    if (($UserId -le 0) -and ($GroupId -le 0)) {
        $introspect = New-Object System.Net.Http.StringContent((@{ apiKey = $apiKey } | ConvertTo-Json -Compress), [System.Text.Encoding]::UTF8, 'application/json')
        $response = $client.PostAsync('https://apis.roblox.com/api-keys/v1/introspect', $introspect).Result
        $body = $response.Content.ReadAsStringAsync().Result
        if (-not $response.IsSuccessStatusCode) {
            throw "Could not read the key's owner (HTTP $([int]$response.StatusCode)); pass -UserId or -GroupId. $body"
        }
        $UserId = [long](($body | ConvertFrom-Json).authorizedUserId)
        Write-Output "Uploading as user $UserId (the owner of the key)."
    }
    $creator = if ($UserId -gt 0) { @{ userId = "$UserId" } } else { @{ groupId = "$GroupId" } }
    $request = @{ assetType = 'Model'; creationContext = @{ creator = $creator } }
    if ($assetId -gt 0) {
        $request.assetId = "$assetId"
    }
    else {
        $request.displayName = "REALSTEEL $Name"
        $request.description = "Robot fighter $Name, generated by art/build_robot.py for REALSTEEL."
    }

    $form = New-Object System.Net.Http.MultipartFormDataContent
    $form.Add((New-Object System.Net.Http.StringContent(($request | ConvertTo-Json -Depth 5 -Compress))), 'request')
    $bytes = New-Object System.Net.Http.ByteArrayContent(, [System.IO.File]::ReadAllBytes($file))
    $bytes.Headers.ContentType = [System.Net.Http.Headers.MediaTypeHeaderValue]::Parse('model/fbx')
    $form.Add($bytes, 'fileContent', "$Name.fbx")
    if ($assetId -gt 0) {
        $message = New-Object System.Net.Http.HttpRequestMessage([System.Net.Http.HttpMethod]::new('PATCH'), "https://apis.roblox.com/assets/v1/assets/$assetId")
        $message.Content = $form
        $response = $client.SendAsync($message).Result
    }
    else {
        $response = $client.PostAsync('https://apis.roblox.com/assets/v1/assets', $form).Result
    }
    $body = $response.Content.ReadAsStringAsync().Result
    if (-not $response.IsSuccessStatusCode) {
        throw "$Name upload failed: HTTP $([int]$response.StatusCode) $body"
    }

    $operation = ($body | ConvertFrom-Json).path
    $newId = 0L
    for ($attempt = 0; $attempt -lt 120 -and $newId -eq 0; $attempt++) {
        Start-Sleep -Seconds 2
        $status = $client.GetAsync("https://apis.roblox.com/assets/v1/$operation").Result.Content.ReadAsStringAsync().Result | ConvertFrom-Json
        if ($status.PSObject.Properties.Name -contains 'done' -and $status.done) {
            if ($status.PSObject.Properties.Name -contains 'error') {
                throw "$Name upload was rejected: $($status.error | ConvertTo-Json -Compress)"
            }
            $newId = [long]$status.response.assetId
        }
    }
    if ($newId -eq 0) {
        throw "$Name upload did not finish in time ($operation)."
    }
}
finally {
    $client.Dispose()
}

$source = [regex]::Replace($source, $pattern, "`${1}$newId`${3}")
[System.IO.File]::WriteAllText($manifest, $source)
Write-Output "$Name`: asset $newId"
Write-Output 'PASS: uploaded; review src/shared/RobotAssets.luau, then run ./scripts/dev.ps1 validate'
